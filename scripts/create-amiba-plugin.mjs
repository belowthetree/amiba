// ============================================================
// 创建本地 Amiba 插件骨架
// 用法：node scripts/create-amiba-plugin.mjs <plugin-id>
// ============================================================
import { existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const ID_PATTERN = /^[a-z][a-z0-9]*(-[a-z0-9]+)*$/

const id = process.argv[2]
if (!id) {
  console.error('用法: node scripts/create-amiba-plugin.mjs <plugin-id>')
  process.exit(1)
}
if (!ID_PATTERN.test(id)) {
  console.error('插件 id 必须是小写 kebab-case，例如 my-plugin')
  process.exit(1)
}

const target = join(ROOT, 'src', 'plugins-local', id)
if (existsSync(target)) {
  console.error(`目标已存在: ${target}`)
  process.exit(1)
}

mkdirSync(join(target, 'src'), { recursive: true })

writeFileSync(join(target, 'amiba.plugin.json'), `${JSON.stringify({
  apiVersion: 1,
  id,
  kind: 'plugin',
  entry: 'src/index.ts',
  inject: ['pageRegistry', 'uiSlots'],
  provides: {
    pages: [id],
    slots: ['ui.slot.settings.section'],
  },
  permissions: { allow: [] },
}, null, 2)}\n`, 'utf8')

writeFileSync(join(target, 'src', 'index.ts'), `// ${id} — 由 create-amiba-plugin 生成
import { defineAmibaPlugin } from '../../../sdk'
import type { AmibaContext } from '../../../kernel'
import type { PageRegistry } from '../../../plugins/page-registry'
import type { UISlotRegistry } from '../../../plugins/ui-slots'
import PluginPage from './PluginPage.vue'

const plugin = defineAmibaPlugin({
  name: '@amiba/${id}',
  inject: ['pageRegistry', 'uiSlots'],
  provides: [],

  apply(ctx: AmibaContext): void {
    const pages = ctx.get<PageRegistry>('pageRegistry')
    const slots = ctx.get<UISlotRegistry>('uiSlots')
    if (!pages || !slots) throw new Error('[${id}] 缺少 pageRegistry / uiSlots 服务')

    const page = pages.register({
      id: '${id}',
      path: '/${id}',
      name: '${id}',
      component: PluginPage,
      title: () => '${id}',
      order: 100,
      mainNav: false,
    })
    ctx.effect(() => page.dispose, '${id}: page')

    const section = slots.register({
      name: 'ui.slot.settings.section',
      id: '${id}:settings',
      order: 100,
      component: PluginPage,
      label: () => '${id}',
    })
    ctx.effect(() => section.dispose, '${id}: settings slot')
  },
})

export const name = plugin.name
export const inject = plugin.inject
export const provides = plugin.provides
export const apply = plugin.apply
`, 'utf8')

writeFileSync(join(target, 'src', 'PluginPage.vue'), `<template>
  <div class="${id}-page">
    <h3>${id}</h3>
    <p>Edit src/PluginPage.vue to start.</p>
  </div>
</template>

<script setup lang="ts">
defineOptions({ name: '${id}' })
</script>

<style scoped>
.${id}-page {
  padding: 16px;
}
</style>
`, 'utf8')

writeFileSync(join(target, 'README.md'), `# ${id}

Generated by create-amiba-plugin.

## Enable

\`\`\`bash
node scripts/amiba-plugin.mjs add ./src/plugins-local/${id}
\`\`\`
`, 'utf8')

console.log(`已创建: ${target}`)
console.log(`下一步: node scripts/amiba-plugin.mjs add ./src/plugins-local/${id}`)
